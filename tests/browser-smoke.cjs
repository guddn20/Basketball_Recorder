// Run with NODE_PATH pointing to a Playwright installation and SAMPLE_VIDEO set.
const {chromium} = require('playwright');
const fs = require('fs');
const path = require('path');
const assert = require('assert/strict');
const url = process.env.COURTSIDE_URL || 'http://127.0.0.1:8765';
const output = path.resolve(__dirname,'../test-results');
fs.mkdirSync(output,{recursive:true});
(async()=>{
  const browser=await chromium.launch({channel:'chrome',headless:true});
  const context=await browser.newContext({viewport:{width:1600,height:1100},acceptDownloads:true});
  const page=await context.newPage();
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  try {
    await page.goto(url,{waitUntil:'domcontentloaded'});
    await page.locator('#workspace:not([hidden])').waitFor();
    await page.waitForFunction(()=>document.querySelector('video').readyState>=2);
    const uploadResponse=page.waitForResponse(r=>r.url().endsWith('/api/upload')&&r.request().method()==='POST');
    await page.locator('#upload-input').setInputFiles({name:'[UI 검증] sample.mp4',mimeType:'video/mp4',buffer:fs.readFileSync(process.env.SAMPLE_VIDEO)});
    const uploaded=await (await uploadResponse).json();
    await page.waitForFunction(id=>localStorage.getItem('courtside-session')===id,uploaded.id);
    await page.locator('#video-name').filter({hasText:'[UI 검증] sample.mp4'}).waitFor();
    await page.waitForFunction(()=>document.querySelector('video').readyState>=2);
    const testId=await page.evaluate(()=>localStorage.getItem('courtside-session'));
    fs.writeFileSync(path.join(output,'ui-session-id.txt'),testId);
    await page.locator('video').evaluate(v=>v.currentTime=4);
    await page.waitForFunction(()=>Math.abs(document.querySelector('video').currentTime-4)<.1);
    await page.locator('#register-player').click();
    let box=await page.locator('#overlay').boundingBox();
    await page.mouse.move(box.x+box.width*.419,box.y+box.height*.513);
    await page.mouse.down();await page.mouse.move(box.x+box.width*.502,box.y+box.height*.846,{steps:10});await page.mouse.up();
    await page.locator('#player-dialog[open]').waitFor();
    await page.locator('#player-name').fill('UI 테스트 선수');
    await page.locator('#player-team').fill('흰색 팀');
    await page.locator('#player-number').fill('7');
    await page.locator('#player-form button[type=submit]').click();
    await page.waitForFunction(()=>document.querySelector('#player-count').textContent==='1');
    await page.locator('#register-hoop').click();
    box=await page.locator('#overlay').boundingBox();
    await page.mouse.move(box.x+box.width*.451,box.y+box.height*.302);
    await page.mouse.down();await page.mouse.move(box.x+box.width*.487,box.y+box.height*.328,{steps:8});await page.mouse.up();
    await page.locator('#hoop-dialog[open]').waitFor();
    await page.locator('#hoop-form button[type=submit]').click();
    await page.locator('.hoop-item').waitFor();
    await page.locator('#footage-mode').selectOption('highlights');
    await page.locator('#new-event').click();
    await page.locator('#event-time').fill('4.2');
    const player=await page.locator('#event-player option').nth(1).getAttribute('value');
    await page.locator('#event-player').selectOption(player);
    await page.locator('#event-result').selectOption('made');
    await page.locator('#event-value').selectOption('2');
    await page.locator('#confirm-event').click();
    await page.waitForFunction(()=>document.querySelector('#boxscore tbody .points')?.textContent==='2');
    await page.locator('#event-value').selectOption('3');
    await page.locator('#confirm-event').click();
    await page.waitForFunction(()=>document.querySelector('#boxscore tbody .points')?.textContent==='3');
    assert.equal(await page.locator('#boxscore tbody td').nth(3).textContent(),'—');
    const downloadPromise=page.waitForEvent('download');
    await page.locator('#export-boxscore').click();
    const download=await downloadPromise;await download.saveAs(path.join(output,'ui-boxscore.csv'));
    const csv=fs.readFileSync(path.join(output,'ui-boxscore.csv'),'utf8');
    assert(csv.includes('미집계'));assert(csv.includes('UI 테스트 선수'));
    await page.reload({waitUntil:'domcontentloaded'});
    await page.waitForFunction(()=>document.querySelector('#boxscore tbody .points')?.textContent==='3');
    await page.locator('#event-filter').selectOption('confirmed');
    await page.locator('.event-item').click();
    await page.locator('#reject-event').click();
    await page.waitForFunction(()=>document.querySelector('#boxscore tbody .points')?.textContent==='0');
    await page.locator('#new-event').click();
    await page.locator('#event-time').fill('8');
    await page.locator('#save-pending').click();
    await page.waitForFunction(()=>document.querySelector('#pending-badge').textContent.includes('확인 필요 1건'));
    assert.equal(await page.locator('#boxscore tbody .points').textContent(),'0');
    await page.locator('#frame-mode-button').click();
    await page.waitForFunction(()=>{const i=document.querySelector('#frame-image');return !i.hidden&&i.complete&&i.naturalWidth>0;});
    await page.locator('#frame-mode-button').click();
    const sampleButton=page.locator('.session-item').filter({hasText:'샘플 · 주황색'});
    await sampleButton.click();
    await page.waitForFunction(()=>document.querySelector('video').readyState>=2);
    await page.locator('video').evaluate(v=>new Promise(resolve=>{v.addEventListener('seeked',resolve,{once:true});v.currentTime=4.1;}));
    await page.waitForFunction(()=>Math.abs(document.querySelector('video').currentTime-4.1)<.15);
    await page.locator('#event-filter').selectOption('pending');
    await page.waitForTimeout(500);
    await page.screenshot({path:path.join(output,'desktop.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:path.join(output,'mobile.png'),fullPage:true});
    const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+1);
    assert.equal(overflow,false,'Page overflows horizontally on mobile');
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({passed:true,checks:['video playback','upload','player rectangle registration','rim rectangle registration','confirmed score','edit without duplicate','CSV download','reload persistence','rejection removes score','pending not counted','frame fallback','mobile width'],testSession:testId,errors,output},null,2));
  }catch(error){
    await page.screenshot({path:path.join(output,'failure.png'),fullPage:true}).catch(()=>{});
    console.error(JSON.stringify({pageErrors:errors,toast:await page.locator('#toast').textContent().catch(()=>''),formValid:await page.locator('#event-form').evaluate(f=>f.checkValidity()).catch(()=>null)}));
    throw error;
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
